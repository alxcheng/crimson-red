#!/usr/bin/env python3
"""Generate main-game/data/bh_items.lua and bh_rewards.lua from bh/data/*.json.

These are the Battleheart tables Crimson Red uses verbatim. Edit the JSON
source (or this script's mapping tables) and re-run — never edit the generated
Lua by hand.   Usage: python3 bh/tools/gen_game_data.py
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")
OUT = os.path.join(HERE, "..", "..", "main-game", "data")
load = lambda n: json.load(open(os.path.join(DATA, n + ".json")))

# usableBy[] is indexed by BH class (0 Cleric .. 9 Paladin). Crimson Red class
# keys for each BH class; a CR class without a BH original borrows one.
BH_CLASS_TO_CR = {
    0: ["cleric"], 1: ["knight"], 2: ["rogue", "brigand"], 3: ["wizard"], 4: ["witch"],
    5: ["piper", "nomad"], 6: ["champion"], 7: ["duelist"], 8: ["hunter", "jester"], 9: ["paladin"],
}

# What a trinket does, by BH item id (bh/systems/party-member-stats-ai-damage.md §4.2).
# Only effects the CR battle engine implements get a stat; the rest are listed
# so the shop can skip them until someone implements them.
TRINKET_EFFECT = {}
for ids, eff in [((12, 13, 14, 15, 16, 17), "power"), ((24, 25, 26), "defense"), ((22, 23, 28), "crit"),
                 ((7, 32), "cooldown"), ((8, 19), "regen"), ((18, 27), "moveSpeed"), ((20, 21), "ward"),
                 ((29, 30, 31), "haste"), ((33, 34, 35), "noCooldown"), ((36, 37), "bonusGold"),
                 ((38, 39), "bonusXP"), ((40, 41, 42), "lifeDrain"), ((46, 47, 48), "bonusHealing")]:
    for i in ids: TRINKET_EFFECT[i] = eff

def lua_str(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'

items = load("items")
tier = {}                                   # item id -> loot tier 1..9 (first table listing it)
for t in load("loot_tables"):
    for i in t["tableContents"]: tier.setdefault(i, t["id"] + 1)

out = ["-- data/bh_items.lua — GENERATED by bh/tools/gen_game_data.py from bh/data/items.json.",
       "-- Do not edit by hand. Battleheart's item table, keyed by BH item id (0-based).",
       "--   name, type (weapon|armor|trinket), power, price (shop buy price; selling pays half),",
       "--   upgrade (BH id of the upgraded item or nil), tier (1..9 loot tier, nil = never drops),",
       "--   usableBy (CR class keys; nil = everyone), effect (trinkets: what `power` adds to),",
       "--   desc (BH description).",
       "", "local ITEMS = {"]
for it in items:
    i = it["id"]
    users = [c for b, ok in enumerate(it["usableBy"]) if ok for c in BH_CLASS_TO_CR[b]]
    everyone = all(it["usableBy"])
    f = ["name = " + lua_str(it["itemName"]), 'type = "%s"' % it["itemType"], "power = %d" % it["power"],
         "price = %d" % it["sellPrice"]]
    if it["upgrade"] >= 0: f.append("upgrade = %d" % it["upgrade"])
    if i in tier: f.append("tier = %d" % tier[i])
    if not everyone: f.append("usableBy = {" + ", ".join(lua_str(c) for c in users) + "}")
    if it["itemType"] == "trinket": f.append('effect = "%s"' % TRINKET_EFFECT.get(i, "unknown"))
    f.append("desc = " + lua_str(it["description"]))
    out.append("    [%d] = { %s }," % (i, ", ".join(f)))
out += ["}", "", "-- Loot tables: which items can appear at which hero level (bh/data/loot_tables.json).",
        "local LOOT_TABLES = {"]
for t in load("loot_tables"):
    out.append("    { name = %s, minLevel = %d, maxLevel = %d, items = {%s} }," % (
        lua_str(t["tableName"]), t["minLevel"], t["maxLevel"], ", ".join(map(str, t["tableContents"]))))
out += ["}", "", "return { ITEMS = ITEMS, LOOT_TABLES = LOOT_TABLES }", ""]
open(os.path.join(OUT, "bh_items.lua"), "w").write("\n".join(out))

g = load("globals")
levels = [l for l in load("maps")[0]["whichLevel"] if not l["arena"] and l["waves"]]
out = ["-- data/bh_rewards.lua — GENERATED by bh/tools/gen_game_data.py from bh/data. Do not edit by hand.",
       "", "return {",
       "    -- XP to go from level 1 to 2, and the per-level growth multipliers",
       "    -- (bh/systems/battle-end-rewards-xp-loot.md, calculateNextLevelXP).",
       "    FIRST_LEVEL_XP = %d," % g["firstLevelXP"],
       "    XP_TABLE = { %s }," % ", ".join("%g" % x for x in g["XPtable"]),
       "",
       "    -- Per-battle rewards of BH's first map, in order. Crimson Red floor N uses",
       "    -- row N (the last row repeats). gold is +/-15% random; xp is per survivor",
       "    -- after the survivor-count multiplier.",
       "    LEVELS = {"]
for l in levels:
    out.append("        { name = %s, gold = %d, xp = %d }," % (lua_str(l["levelName"]), l["goldReward"], l["XPReward"]))
out += ["    },", "}", ""]
open(os.path.join(OUT, "bh_rewards.lua"), "w").write("\n".join(out))
print("wrote bh_items.lua (%d items), bh_rewards.lua (%d levels)" % (len(items), len(levels)))
