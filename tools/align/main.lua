-- tools/align — measures where each sprite really is inside its (much larger) frame.
--
-- Sprite frames are big so effects have room; the visible character is a small
-- part of the frame, and not centred. This tool looks at every pixel of each
-- sprite's IDLE sheet (all frames) and records the box around the visible
-- pixels. The game then derives everything from that box and ONE number per
-- unit (`scale` in data/classes.lua / data/enemies.lua):
--     body box size = visible box x scale
--     the sprite is drawn so its visible box sits exactly on the body box
--     (so the feet touch the bottom edge of the box)
-- See encounter/entities.lua (addBaseComponents).
--
-- Run ./align_sprites from the repo root after adding or changing a sprite
-- sheet. It rewrites main-game/data/sprite_bounds.lua (never edit that by hand)
-- and prints what it measured.
--
-- A pixel counts as visible when its alpha is above ALPHA_MIN. Columns/rows
-- with fewer than MIN_PIXELS visible pixels (summed over all idle frames) at
-- the edges are ignored, so a stray pixel or a wisp does not stretch the box.

local ALPHA_MIN, MIN_PIXELS = 0.3, 2

-- Hand corrections, by sprite name, for sprites whose pixels do not tell the whole story:
--   top   = first frame row that belongs to the BODY. Everything above it (a tall staff,
--           a banner) is ignored, so the box ends at the head like everyone else's.
--   float = empty art pixels to leave under the sprite: a flying unit hovers that far
--           above its feet line (its shadow and its place in the fight stay on the ground).
local OVERRIDES = {
    Nomad = { top = 113 },   -- the witch: her staff's flame rises far above her hood
    Bat   = { float = 14 },  -- flies
}

local function readImage(path)
    local f = assert(io.open(path, "rb"), "cannot read " .. path)
    local bytes = f:read("*a"); f:close()
    return love.image.newImageData(love.filesystem.newFileData(bytes, path))
end

-- Visible box of a sheet of `frames` frames, each fw x fh: x, y, w, h in frame pixels.
local function measure(path, frames, fw, fh, fix)
    local img = readImage(path)
    local cols, rows = {}, {}
    for f = 0, frames - 1 do
        for y = fix.top or 0, fh - 1 do
            for x = 0, fw - 1 do
                local _, _, _, a = img:getPixel(f * fw + x, y)
                if a > ALPHA_MIN then
                    cols[x] = (cols[x] or 0) + 1
                    rows[y] = (rows[y] or 0) + 1
                end
            end
        end
    end
    local x0, x1, y0, y1
    for x = 0, fw - 1 do if (cols[x] or 0) >= MIN_PIXELS then x0 = x0 or x; x1 = x end end
    for y = 0, fh - 1 do if (rows[y] or 0) >= MIN_PIXELS then y0 = y0 or y; y1 = y end end
    if not x0 then return nil end
    return x0, y0, x1 - x0 + 1, y1 - y0 + 1 + (fix.float or 0)
end

function love.load(args)
    local root = args[1]
    local ok, err = pcall(function()
        local sheets = dofile(root .. "/main-game/data/sprites.lua")
        local out = {
            "-- data/sprite_bounds.lua — GENERATED by ./align_sprites (tools/align/main.lua). Do not edit by hand.",
            "--",
            "-- For each sprite: the frame size and the box around the VISIBLE pixels of its idle",
            "-- animation, in frame pixels ({x, y} = top-left corner inside the frame).",
            "",
            "return {",
        }
        print(("%-10s %-9s %-22s %s"):format("sprite", "frame", "visible box (x y w h)", "feet row / centre column"))
        for _, row in ipairs(sheets) do
            local name = row[1]:match("^(.*)Idle$")
            if name then
                local fw, fh = row[4], row[5]
                local x, y, w, h = measure(root .. "/main-game/assets/" .. row[2], row[3], fw, fh, OVERRIDES[name] or {})
                assert(x, "no visible pixels in " .. row[2])
                out[#out + 1] = ("    %-9s = { fw = %d, fh = %d, x = %d, y = %d, w = %d, h = %d },"):format(name, fw, fh, x, y, w, h)
                print(("%-10s %3dx%-5d %3d %3d %3d %3d %12d / %.1f"):format(name, fw, fh, x, y, w, h, y + h, x + w / 2))
            end
        end
        out[#out + 1] = "}"
        out[#out + 1] = ""
        local f = assert(io.open(root .. "/main-game/data/sprite_bounds.lua", "w"))
        f:write(table.concat(out, "\n")); f:close()
        print("wrote main-game/data/sprite_bounds.lua")
    end)
    if not ok then print("align_sprites: " .. tostring(err)) end
    love.event.quit(ok and 0 or 1)
end
